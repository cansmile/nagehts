            function rfchk(th, io) {
                var q, qn, a, b, fl;
                a = $.trim(th.val()).replace(/\s+/g, "");
                q = a.length;
                qn = (th.attr("id").substr(4)) - 1;
                if (!$.isArray(an[qn])) {
                   /* 1 인 경우 */
                    if (io) {
                        b = an[qn];
                    } else {
                        b = an[qn].replace(/\s+/g, "").substr(0, q);
                    }
                    b = b.replace(/\s+/g, "");

                    if (a == b) {
                        return true;
                    }

                } else {
                   /* 2 이상인 경우 */
                    for (var fd = 0; fd < an[qn].length; fd++) {
                        if (io) {
                            b = an[qn][fd];
                        } else {
                            b = an[qn][fd].replace(/\s+/g, "").substr(0, q);
                        }
                        b = b.replace(/\s+/g, "");

                        if (a == b) {
                            return true;
                        }
                    }

                }
